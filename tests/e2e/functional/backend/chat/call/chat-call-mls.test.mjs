const member = client => ({ clientId: client.clientId, bundle: client.bundle() });
test('a pre-join application message is ignored and current authenticated messages remain usable', async () => {
  const { alice, bob, carol, commits } = await group();
  try {
    await alice.reconcile([member(alice), member(bob)]);
    await bob.accept(commits.shift());
    const earlier = await alice.encrypt({ offer: 'before-carol-joined' });
    await alice.reconcile([member(alice), member(bob), member(carol)]);
    const added = commits.shift(); await bob.accept(added); await carol.accept(added);
    assert.equal(await carol.decrypt(earlier), null);
    const current = await alice.encrypt({ offer: 'current-authenticated-epoch' });
    assert.deepEqual(await carol.decrypt(current), { clientId: alice.clientId, plaintext: JSON.stringify({ offer: 'current-authenticated-epoch' }) });
  } finally { await Promise.all([alice, bob, carol].map(client => client.destroy())); }
});
async function group() {
  const commits = [], callId = crypto.randomUUID();
  const alice = await ChatCallMls.create(callId, async bundle => { commits.push(bundle); });
  const bobCommits = [], bob = await ChatCallMls.create(callId, async bundle => { bobCommits.push(bundle); });
  const carol = await ChatCallMls.create(callId, async () => { throw new Error('Not coordinator'); });
  return { alice, bob, carol, commits, bobCommits };
}

test('MLS Welcome joins three participants and authenticates group messages', async () => {
  const { alice, bob, carol, commits } = await group();
  try {
    await alice.reconcile([member(alice)]);
    await alice.reconcile([member(alice), member(bob)]);
    await bob.accept(commits.shift());
    await alice.reconcile([member(alice), member(bob), member(carol)]);
    const added = commits.shift(); await bob.accept(added); await carol.accept(added);
    assert.equal(await alice.verificationCode(), await bob.verificationCode());
    assert.equal(await bob.verificationCode(), await carol.verificationCode());
    for (let i = 0; i < 8; i++) {
      const encrypted = await alice.encrypt({ target: 'bob', offer: i });
      assert.deepEqual(await bob.decrypt(encrypted), { clientId: alice.clientId, plaintext: JSON.stringify({ target: 'bob', offer: i }) });
      await carol.decrypt(encrypted);
      const reply = await bob.encrypt({ answer: i }); await alice.decrypt(reply); await carol.decrypt(reply);
    }
  } finally { await Promise.all([alice, bob, carol].map(client => client.destroy())); }
});

test('MLS rejects tampering, replay and another call while valid messages continue', async () => {
  const { alice, bob, carol, commits } = await group();
  const foreign = await ChatCallMls.create(crypto.randomUUID(), async () => {});
  try {
    await alice.reconcile([member(alice), member(bob)]); await bob.accept(commits.shift());
    const encrypted = await alice.encrypt({ secret: 'offer' });
    const changed = decodeCallBytes(encrypted); changed[changed.length - 1] ^= 1;
    await assert.rejects(bob.decrypt(encodeCallBytes(changed)));
    await bob.decrypt(encrypted); await assert.rejects(bob.decrypt(encrypted));
    assert.equal((await bob.decrypt(await alice.encrypt({ answer: 'next' }))).plaintext, '{"answer":"next"}');
    await foreign.reconcile([member(foreign)]);
    await assert.rejects(bob.decrypt(await foreign.encrypt({ wrongCall: true })));
    await assert.rejects(carol.accept({ commit: encrypted, members: [alice.clientId, carol.clientId] }));
  } finally { await Promise.all([alice, bob, carol, foreign].map(client => client.destroy())); }
});

test('the surviving coordinator removes a departed member and rotates group keys', async () => {
  const { alice, bob, carol, commits, bobCommits } = await group();
  try {
    await alice.reconcile([member(alice), member(bob), member(carol)]);
    const welcome = commits.shift(); await bob.accept(welcome); await carol.accept(welcome);
    const oldCode = await bob.verificationCode();
    await bob.reconcile([member(bob), member(carol)]); await carol.accept(bobCommits.shift());
    assert.notEqual(oldCode, await bob.verificationCode());
    assert.equal(await bob.verificationCode(), await carol.verificationCode());
    const ciphertext = await bob.encrypt({ coordinator: 'bob' });
    assert.equal((await carol.decrypt(ciphertext)).clientId, bob.clientId);
    await assert.rejects(alice.decrypt(ciphertext));
    await assert.rejects(bob.validateMembers([bob.clientId, alice.clientId]));
  } finally { await Promise.all([alice, bob, carol].map(client => client.destroy())); }
});


test('a rejected commit stays unmerged and leaves the crypto engine usable', async () => {
  let rejected = true;
  const commits = [], callId = crypto.randomUUID();
  const alice = await ChatCallMls.create(callId, async bundle => {
    if (rejected) throw new Error('Signaling unavailable');
    commits.push(bundle);
  });
  const bob = await ChatCallMls.create(callId, async () => {});
  try {
    await alice.reconcile([member(alice)]);
    await assert.rejects(alice.reconcile([member(alice), member(bob)]));
    assert.deepEqual(await alice.memberIds(), [alice.clientId]);
    rejected = false;
    await alice.reconcile([member(alice), member(bob)]);
    await bob.accept(commits.shift());
    assert.equal((await bob.decrypt(await alice.encrypt({afterRejection:true}))).plaintext, '{"afterRejection":true}');
  } finally { await Promise.all([alice.destroy(), bob.destroy()]); }
});

test('leaving during an in-flight membership commit releases the crypto engine without a WASM trap', async () => {
  const sending = Promise.withResolvers(), commit = Promise.withResolvers();
  const alice = await ChatCallMls.create(crypto.randomUUID(), async () => {
    sending.resolve();await commit.promise;
  });
  const bob = await ChatCallMls.create(crypto.randomUUID(), async () => {});
  await alice.reconcile([member(alice)]);
  const reconcile = alice.reconcile([member(alice), member(bob)]);
  const rejected = assert.rejects(reconcile);
  await sending.promise;
  const destroyed = alice.destroy();
  commit.reject(new Error('Call ended'));
  await rejected;await destroyed;await bob.destroy();
  const next = await ChatCallMls.create(crypto.randomUUID(), async () => {});
  try { await next.reconcile([member(next)]);assert.deepEqual(await next.memberIds(),[next.clientId]); }
  finally { await next.destroy(); }
});
